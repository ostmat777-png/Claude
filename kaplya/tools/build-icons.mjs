// Regenerates src/renderer/js/icons.js from the Lucide icon set (ISC licence).
//
//   npm install --no-save lucide-static
//   node tools/build-icons.mjs [path/to/lucide-static/icons]
//
// Only the icons listed below are copied, so the app carries no icon package.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = process.argv[2] || path.join(here, '..', 'node_modules', 'lucide-static', 'icons');
const out = path.join(here, '..', 'src', 'renderer', 'js', 'icons.js');

const names = `
house clipboard-list inbox type notebook-pen cloud-sun sliders-horizontal message-circle pin pin-off settings
search x check copy trash-2 play pause skip-back skip-forward volume-2 volume-1 volume-x volume crop monitor
scan-text qr-code pipette eraser video terminal command square circle wifi wifi-off bluetooth bluetooth-off moon
sun lock power rotate-cw moon-star timer bell plus chevron-right chevron-left chevron-down external-link
folder-open image file link refresh-cw arrow-up-right pencil highlighter grid-3x3 undo-2 redo-2 save wind
droplets droplet gauge sunrise sunset umbrella thermometer cloud cloud-rain cloud-snow cloud-lightning cloud-fog
cloud-drizzle cloud-moon map-pin music mic languages calculator app-window globe keyboard star maximize-2
grip-vertical signal list-checks case-sensitive braces binary sparkles navigation hourglass alarm-clock
rotate-ccw info triangle-alert mic-vocal arrow-right clipboard clipboard-paste shield-check eye-off
mouse-pointer-2 blend circle-stop download wrap-text space arrow-down-a-z clock log-out layout-grid scissors
sun-moon wand-sparkles files zap corner-down-left calendar-clock list bell-ring at-sign
heart list-music chevron-up map layers folder link-2 arrow-left arrow-left-right maximize minimize-2 snowflake
radio picture-in-picture-2 monitor-play square-check-big check-check ellipsis tv folder-plus eye circle-play
expand shrink chart-line chart-no-axes-column mouse-pointer-click
`.split(/\s+/).filter(Boolean);

const icons = {};
for (const name of names) {
  const svg = fs.readFileSync(path.join(src, name + '.svg'), 'utf8');
  const body = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<svg[\s\S]*?>/, '')
    .replace(/<\/svg>/, '')
    .replace(/\s*\n\s*/g, '')
    .replace(/\s+\/>/g, '/>')
    .trim();
  icons[name] = body;
}

const lines = Object.keys(icons).sort().map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(icons[k])},`);
const text = `// Generated by tools/build-icons.mjs. Do not edit by hand.
//
// Icon shapes come from Lucide (https://lucide.dev), ISC License:
// Copyright (c) Lucide Icons and Contributors. Some icons derive from Feather
// (MIT License, Copyright (c) 2013-present Cole Bemis).

export const ICONS = {
${lines.join('\n')}
};

/** An <svg> element for the named icon. */
export function icon(name, size = 16, strokeWidth = 1.8) {
  const body = ICONS[name] || ICONS.circle;
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('width', size);
  svg.setAttribute('height', size);
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', strokeWidth);
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  svg.setAttribute('aria-hidden', 'true');
  svg.classList.add('icon');
  svg.dataset.icon = name;
  svg.innerHTML = body;
  return svg;
}
`;
fs.writeFileSync(out, text);
console.log(`wrote ${Object.keys(icons).length} icons to ${path.relative(process.cwd(), out)}`);
